"""Writes src/namespace.h from the globals of a library built without it (make namespace).

Every global the library defines becomes either its public name from tools/public_api.txt or
psi_<name>, so a program linking the library meets only ps_ and psi_ symbols. The header is
force-included (-include) in every library, test and CLI file; new globals need a rerun.

    python3 tools/gen_namespace.py NM_OUTPUT > src/namespace.h
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# system headers first, so a rename can never reach a declaration inside one (not complex.h: its I macro)
SYSTEM = ["assert.h", "ctype.h", "float.h", "limits.h", "math.h", "stdarg.h", "stdbool.h",
          "stddef.h", "stdint.h", "stdio.h", "stdlib.h", "string.h", "time.h", "gmp.h"]


def public_names():
    """internal -> public, from tools/public_api.txt"""
    table = {}
    for line in open(os.path.join(HERE, "public_api.txt")):
        if line.strip() and not line.startswith("#"):
            old, new = line.split()
            table[old] = new
    return table


def defined_globals(nm_path):
    """the external symbols defined in the nm listing (text, data, bss, common), without macOS's _"""
    names = set()
    for line in open(nm_path):
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TDBSC":
            names.add(parts[2][1:] if sys.platform == "darwin" else parts[2])
    return names


def main():
    table, names = public_names(), defined_globals(sys.argv[1])
    missing = sorted(set(table) - names)
    if missing:
        sys.exit("public names not defined by the library: " + " ".join(missing))
    out = ["// Generated by tools/gen_namespace.py (make namespace): do not edit.",
           "// Maps each library global to its public ps_ name or to psi_<name>.",
           "#ifndef PS_NAMESPACE_H", "#define PS_NAMESPACE_H", ""]
    out += [f"#include <{h}>" for h in SYSTEM] + [""]
    for n in sorted(names):
        if not n.startswith(("ps_", "psi_")):
            out.append(f"#define {n} {table.get(n, 'psi_' + n)}")
    out += ["", '#include "polysolver.h"', "", "#endif", ""]
    sys.stdout.write("\n".join(out))


main()
